def vec_add(*vectors):
    return tuple(sum(components) for components in zip(*vectors))


def vec_scale(v, s):
    return tuple(s * c for c in v)


def vec_cross(a, b):
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def face_normal(normal_id: int) -> tuple:
    if normal_id == 0:
        return (1, 0, 0)
    if normal_id == 1:
        return (-1, 0, 0)
    if normal_id == 2:
        return (0, 1, 0)
    if normal_id == 3:
        return (0, -1, 0)
    if normal_id == 4:
        return (0, 0, 1)
    return (0, 0, -1)

def get_base_primitive(mesh_polygon_id: int, root_id: int) -> list:
    normal = face_normal(mesh_polygon_id)
    axis_a = (normal[1], normal[2], normal[0])  # normal.yzx swizzle
    axis_b = vec_cross(normal, axis_a)

    b1b2 = root_id
    b1 = b1b2 >> 1
    b2 = b1b2 & 1

    l0 = 2 * b2 - 1
    r0 = 2 * b1 - 1
    l1 = -r0
    r1 = l0

    base_primitive = [
        vec_add(vec_scale(axis_a, l0), vec_scale(axis_b, l1), normal),
        vec_add(vec_scale(axis_a, r0), vec_scale(axis_b, r1), normal),
        normal,
    ]

    return base_primitive


